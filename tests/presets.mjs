import {chromium,expect} from '@playwright/test';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const data=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('real_life_quest_state_v1_family')));
try {
  await page.goto('http://localhost:5173');
  await page.getByRole('button',{name:'Get Started'}).click();
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await page.getByRole('button',{name:"I'm a Parent"}).click();
  await page.getByLabel('Child’s hero name').fill('Leo');
  await page.getByLabel('Create a parent PIN').fill('1234');
  await page.getByLabel('Confirm PIN').fill('1234');
  await page.getByRole('button',{name:'Create Family'}).click();
  await page.getByRole('button',{name:/Ready-made routines & tasks/}).click();
  await expect(page.getByRole('heading',{name:'A routine that fits your child'})).toBeVisible();
  await page.screenshot({path:'artifacts/preset-library.png'});
  const before=(await data()).quests.length;
  await page.getByRole('button',{name:/Sleepy-time stars/}).click();
  await expect(page.getByRole('heading',{name:'2 tasks selected'})).toBeVisible();
  expect((await data()).quests.length).toBe(before);
  await page.getByRole('button',{name:'Allow 2 Tasks'}).click();
  expect((await data()).quests.length).toBe(before+2);
  await page.getByRole('button',{name:'Preset Library',exact:true}).click();
  await expect(page.getByRole('button',{name:/Sleepy-time stars/})).toBeDisabled();
  await page.getByLabel('Age guide').selectOption('6-8');
  await page.getByLabel('Search presets').fill('sweep');
  await expect(page.getByText('No matching ideas yet')).toBeVisible();
  await page.getByLabel('Age guide').selectOption('9-12');
  await expect(page.getByRole('heading',{name:'Sweep a Small Floor Area'})).toBeVisible();
  await page.getByLabel('Search presets').fill('socks');
  await page.getByRole('button',{name:'Select Match the Socks',exact:true}).click();
  await page.getByRole('button',{name:'Allow 1 Task',exact:true}).click();
  await page.getByRole('button',{name:'One-time',exact:true}).click();
  await expect(page.getByRole('switch',{name:'Enable Match the Socks'})).toBeChecked();
  await page.getByRole('button',{name:'Custom Task',exact:true}).click();
  await page.getByLabel('Name',{exact:true}).fill('Put Art Supplies Away');
  await page.getByLabel('Instructions').fill('Put crayons and paper in the blue box.');
  await page.getByRole('dialog').locator('select[name="category"]').selectOption('Tidy & Order');
  await page.getByRole('dialog').locator('select[name="days"]').selectOption('Once');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await expect(page.getByRole('switch',{name:'Enable Put Art Supplies Away'})).toBeChecked();
  await page.screenshot({path:'artifacts/preset-custom-tasks.png'});
  await page.getByRole('button',{name:'More',exact:true}).click();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('button',{name:'Switch to child'}).click();
  await page.getByRole('button',{name:"I'm a Kid"}).click();
  await page.getByRole('button',{name:/Bedtime Wind-Down/}).click();
  await page.getByRole('button',{name:/Brush Teeth Before Bed/}).click();
  await page.clock.install();
  await page.getByRole('button',{name:'Start brushing'}).click();
  await page.clock.fastForward(120001);
  await page.getByRole('button',{name:'Submit Quest',exact:true}).click();
  const brushed=await data();
  expect(brushed.quests.find(q=>q.presetId==='evening-teeth').status).toBe('waiting');
  expect(brushed.quests.find(q=>q.id==='teeth').status).toBe('active');
  await page.getByRole('button',{name:/Put Art Supplies Away/}).click();
  await page.getByRole('button',{name:'I’ve Finished!'}).click();
  expect((await data()).quests.find(q=>q.name==='Put Art Supplies Away').status).toBe('waiting');
  await page.reload();
  expect((await data()).quests.some(q=>q.presetId==='evening-teeth')).toBe(true);
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('button',{name:'Parent access'}).click();
  await page.getByRole('button',{name:"I'm a Parent"}).click();
  await page.getByLabel('Parent PIN',{exact:true}).fill('1234');
  await page.getByRole('button',{name:'Unlock',exact:true}).click();
  await page.getByRole('button',{name:/Ready-made routines & tasks/}).click();
  await page.setViewportSize({width:320,height:640});
  await page.getByLabel('Search presets').fill('water');
  await page.screenshot({path:'artifacts/preset-small-mobile.png'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  console.log('PASS: parent-only library, pack review, duplicate prevention, age filters, one-time preset, custom task, bedtime timer targeting, child visibility, persistence and 320px layout.');
} catch(error) {
  await page.screenshot({path:'artifacts/preset-test-failure.png'});
  throw error;
} finally {await browser.close();}
